/** Первая строка их умолчательного текста — по ней он и узнаётся.
 *
 * Не всё сравнение целиком: их текст между версиями ядра меняется, а вот
 * самопредставление в начале — то, ради чего находка и заведена. Достаточно
 * узкая, чтобы не задеть текст, который человек написал сам. */
const THEIR_DEFAULT_OPENING = "You are Hermes Agent";

/**
 * Кладёт наш SOUL.md в профиль, если там ещё нет своего.
 *
 * Четыре случая, и разница между ними — вся суть:
 *   - файла нет → пишем свой (иначе его напишет ядро, и уже чужим именем);
 *   - лежит ИХ умолчательный → перезаписываем: своего замысла в нём ноль, это
 *     ровно тот текст, из-за которого находка заведена;
 *   - лежит НАШ ПРЕЖНИЙ умолчательный → перезаписываем: его писали мы, не человек;
 *   - лежит что-то ещё → НЕ ТРОГАЕМ. Человек мог написать это сам, и потерять
 *     его настройку было бы хуже, чем оставить чужое имя.
 *
 * @returns что было сделано — для журнала и для теста.
 */
export function ensureOurSoul(homeDir) {
  const soulPath = path.join(homeDir, "SOUL.md");

  let existing = null;
  try {
    existing = fs.readFileSync(soulPath, "utf-8");
  } catch {
    // Файла нет либо он нечитаем — оба случая ниже лечатся одинаково.
  }

  const ours = existing !== null && existing.trim() === PREVIOUS_AEC_SOUL_MD;
  if (existing !== null && !ours && !existing.trimStart().startsWith(THEIR_DEFAULT_OPENING)) {
    return "kept";
  }

  const wrote = existing === null ? "written" : "replaced";
  fs.mkdirSync(homeDir, { recursive: true });
  fs.writeFileSync(soulPath, AEC_SOUL_MD, "utf-8");

  return wrote;
}
