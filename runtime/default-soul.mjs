// Наш умолчательный SOUL.md вместо чужого (находка D-58, SPEC C12).
//
// ЧТО ТАКОЕ SOUL.md. Файл в профиле агента, чей текст ядро вклеивает в начало
// системного промпта каждого разговора, — то самое «кто ты такой», что агент
// читает раньше всего остального.
//
// ЧТО БЫЛО НЕ ТАК. При первом запуске ядро создаёт этот файл САМО и пишет туда
// «You are Hermes Agent, an intelligent AI assistant created by Nous Research…»
// (`hermes_cli/default_soul.py`). Чужое имя продукта и чужой владелец — в файле,
// который человек открывает и правит. C12 запрещает это прямо.
//
// ПОЧЕМУ ЭТО РАБОТАЕТ И ПЕРЕЖИВЁТ ПОДЪЁМ ПИНА. Их `_ensure_default_soul_md`
// (`hermes_cli/config.py`) пишет файл ТОЛЬКО если его нет — или если лежащий
// текст совпадает с одним из их же старых пустых шаблонов. Значит достаточно
// положить свой раньше них: ни одной строки их исходников мы не трогаем.
//
// РАЗВИЛКА AGENTS §9 ПРОЙДЕНА ЯВНО: изменение продуктового промпта закрыто
// ВАРИАНТОМ Б — записанным отказом от эвала. Решение владельца 2026-08-31,
// ответственность его; основание — текст ниже не задаёт поведения, только имя
// и область. Прецедент того же владельца: 2026-08-17, строка про язык.

import fs from "node:fs";
import path from "node:path";

/** Текст, который агент читает первым.
 *
 * Намеренно без единой инструкции о поведении. Их вариант, помимо имени, задаёт
 * ещё и манеру («direct», «prioritize being useful over being verbose», «be
 * targeted and efficient») — это выброшено: чем меньше в тексте поведения, тем
 * меньше у изменения поводов что-то сломать, и тем честнее отказ от эвала.
 *
 * Строка про язык — решение владельца от 2026-08-17 (бывшая находка D-3): язык
 * общения агента живёт именно здесь, в файле профиля. Кому нужно иначе — правит
 * файл руками, это и был весь замысел.
 */
export const AEC_SOUL_MD =
  "Ты — AECPilot, помощник по проектной документации. " +
  "Ты помогаешь искать и сверять сведения в документах проекта, отвечать на " +
  "вопросы по ним, готовить и править тексты, а также выполнять действия " +
  "своими инструментами. Отвечай по-русски.";

/** Первая строка их умолчательного текста — по ней он и узнаётся.
 *
 * Не всё сравнение целиком: их текст между версиями ядра меняется, а вот
 * самопредставление в начале — то, ради чего находка и заведена. Достаточно
 * узкая, чтобы не задеть текст, который человек написал сам. */
const THEIR_DEFAULT_OPENING = "You are Hermes Agent";

/**
 * Кладёт наш SOUL.md в профиль, если там ещё нет своего.
 *
 * Три случая, и разница между ними — вся суть:
 *   - файла нет → пишем свой (иначе его напишет ядро, и уже чужим именем);
 *   - лежит ИХ умолчательный → перезаписываем: своего замысла в нём ноль, это
 *     ровно тот текст, из-за которого находка заведена;
 *   - лежит что-то ещё → НЕ ТРОГАЕМ. Человек мог написать это сам, и потерять
 *     его настройку было бы хуже, чем оставить чужое имя.
 *
 * @returns что было сделано — для журнала и для теста.
 */
export function ensureOurSoul(homeDir) {
  const soulPath = path.join(homeDir, "SOUL.md");

  let existing = null;
  try {
    existing = fs.readFileSync(soulPath, "utf-8");
  } catch {
    // Файла нет либо он нечитаем — оба случая ниже лечатся одинаково.
  }

  if (existing !== null && !existing.trimStart().startsWith(THEIR_DEFAULT_OPENING)) {
    return "kept";
  }

  const wrote = existing === null ? "written" : "replaced";
  fs.mkdirSync(homeDir, { recursive: true });
  fs.writeFileSync(soulPath, AEC_SOUL_MD, "utf-8");

  return wrote;
}
