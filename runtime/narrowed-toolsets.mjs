import fs from "node:fs";
import path from "node:path";

/** Верхнеуровневый ключ в их YAML: строка начинается с самого имени. */
const NARROWING_KEY = /^platform_toolsets:/;

/**
 * Ищет в `config.yaml` профиля блок, сужающий набор инструментов агента.
 *
 * Отдельная чистая функция, потому что проверять надо ТЕКСТ: разбирать YAML
 * ради одного ключа значит принести зависимость и потерять комментарии, а
 * ключ этот — верхнеуровневый и однострочный.
 *
 * @returns {null | string} текст предупреждения либо `null`, если всё чисто.
 */
export function narrowingWarning(configText) {
  const line = configText.split("\n").find((entry) => NARROWING_KEY.test(entry));
  if (!line) return null;

  return [
    "aecpilot: профиль ядра содержит `platform_toolsets` — набор инструментов агента СУЖЕН.",
    "  Ядро читает разрешённые наборы именно оттуда, и всё, чего нет в этом списке,",
    "  модели не предлагается — без единой ошибки (замечание D-66: было 8 наборов из 19).",
    "  Замеры и живые прогоны против такого профиля мерят обрезанного агента.",
    "  Поставить это могли их мастер установки «Blank Slate» или команда `hermes tools`.",
    "  Если это не ваш выбор — уберите блок из config.yaml; мы его не трогаем.",
  ].join("\n");
}

/**
 * Читает `config.yaml` профиля и, если он сужает агента, печатает
 * предупреждение в stderr.
 *
 * Отсутствие файла — не повод для шума: на первом запуске его ещё нет, ядро
 * создаст его само.
 *
 * @returns {null | string} напечатанный текст либо `null`.
 */
export function warnIfToolsetsNarrowed(homeDir, log = console.warn) {
  let text;
  try {
    text = fs.readFileSync(path.join(homeDir, "config.yaml"), "utf-8");
  } catch {
    return null;
  }

  const warning = narrowingWarning(text);
  if (warning) log(warning);
  return warning;
}
