"""Секрет в тексте, который вот-вот уедет в память (задача 5.3).

Спека `specs/agent-memory.md`, негативный сценарий «Фильтр секретов»: строка,
похожая на ключ, пароль или токен, не сохраняется НИ В ОДНОМ из слоёв — в том
числе когда человек сам просит её запомнить.

ПОЧЕМУ ЭТО НАШ КОД, А НЕ НАСТРОЙКА ЯДРА (замерено 2026-09-09):
  · слой 1 сканируется до записи и умеет отказать (`tools/memory_tool.py`,
    `_scan_memory_content`), но их библиотека `tools/threat_patterns.py` — про
    ИНЪЕКЦИИ и утечку промпта, про секреты там нет ничего, а список зашит в
    модуль и внешней точки расширения не имеет;
  · слой 2 не сканируется вовсе: `mem0_add` кладёт `content` в хранилище как
    есть;
  · `on_memory_write` у провайдера — уведомление ПОСЛЕ записи, отказать им
    нельзя;
  · их гейт подтверждения (`tools/write_approval.py`) умеет только «включён или
    нет», а на пути шлюза паркует КАЖДУЮ запись на подтверждение.

ЧТО ЛОВИМ И ЧЕГО НЕ ЛОВИМ. Ловится ЗНАЧЕНИЕ, а не разговор о нём: «пароль от
почты храню в менеджере» — обычный факт и остаётся, «пароль: Qwerty12345!» —
секрет и не остаётся. Иначе фильтр вырезал бы половину осмысленных записей и его
бы отключили, а выключенный фильтр не защищает ни от чего.
"""

from __future__ import annotations

import re

# (регулярное выражение, id находки). id попадает в текст отказа: агенту надо
# знать, ЧТО именно не пустили, чтобы переписать запись без секрета.
_PATTERNS: list[tuple[re.Pattern, str]] = [
    # Ключи известной формы. Их узнаёшь по приставке, и ложных срабатываний
    # здесь почти не бывает.
    (re.compile(r"\bsk-[A-Za-z0-9_-]{16,}"), "openai_key"),
    (re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{20,}"), "github_token"),
    (re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}"), "slack_token"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "aws_access_key"),
    (re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b"), "google_api_key"),
    (re.compile(r"\bhf_[A-Za-z0-9]{20,}"), "huggingface_token"),
    # Закрытый ключ — целиком по заголовку блока.
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), "private_key"),
    # JWT: три части через точку, первая всегда начинается с заголовка `{"alg"`
    # в base64url, то есть с `eyJ`.
    (re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"), "jwt"),
    # Пароль в строке подключения: `//пользователь:пароль@хост`.
    (re.compile(r"://[^\s:/@]+:[^\s:/@]{4,}@[^\s/]+"), "connection_string_password"),
    # Заголовок авторизации.
    (
        re.compile(r"(?i)\bauthorization\s*:\s*(?:bearer|basic)\s+[A-Za-z0-9._~+/=-]{12,}"),
        "auth_header",
    ),
    # НАЗВАНИЕ РЯДОМ СО ЗНАЧЕНИЕМ. Именно здесь легко переусердствовать, поэтому
    # требуется всё сразу: слово-название, разделитель и НЕПРОБЕЛЬНОЕ значение
    # длиной от восьми знаков, в котором есть и буква, и цифра. «пароль знает
    # только бухгалтерия» под это не подходит, «password = Qwerty12345» — да.
    (
        re.compile(
            r"(?i)\b(?:пароль|password|passwd|api[\s_-]?key|apikey|secret|token|"
            r"ключ\s+доступа|access[\s_-]?key|client[\s_-]?secret)\b\s*[:=]\s*"
            r"[\"']?(?=[^\s\"']*[A-Za-z])(?=[^\s\"']*\d)[^\s\"']{8,}"
        ),
        "labelled_secret",
    ),
]


def find_secrets(text: str) -> list[str]:
    """Идентификаторы находок в порядке объявления. Пусто — секретов не видно."""
    if not text:
        return []

    found: list[str] = []
    for pattern, name in _PATTERNS:
        if pattern.search(text) and name not in found:
            found.append(name)

    return found


def refusal_message(found: list[str]) -> str:
    """Текст отказа для агента: что именно не пустили и что с этим делать.

    Сам секрет в сообщение НЕ ПОПАДАЕТ — иначе он уехал бы в переписку, из
    которой его и не пускали.
    """
    return (
        "AECPilot не сохраняет секреты в память "
        f"(найдено: {', '.join(found)}). "
        "Запись отклонена целиком. Перескажите факт без самого значения — "
        "например «ключ доступа лежит в менеджере паролей», — и повторите."
    )
