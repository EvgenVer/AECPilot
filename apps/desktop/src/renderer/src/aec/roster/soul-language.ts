// Правило языка общения агента — задача 5.14, третий уровень SPEC G7.
//
// Решение владельца 2026-08-17 (бывшая находка D-3): язык, на котором агент
// РАЗГОВАРИВАЕТ, — настройка пользователя, а файл пользователя у ядра один:
// SOUL профиля. Не проектный AGENTS.md: тот путешествует с проектом, а
// настройка — с человеком. Формулировка решения: «строка пишется, а если
// человеку надо иначе — он правит файл сам».
//
// Эвал на это изменение промпта не проводится — waiver владельца, его
// ответственность (AGENTS §9, обязательная развилка закрыта вариантом Б).
// Поэтому здесь ровно строка про язык и ничего больше: персона, тон и правила
// работы в waiver не входят и сюда не дописываются.
//
// Почему язык берётся из локали интерфейса. Это ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ в поле,
// которое человек видит и правит, а не связь двух настроек. Связать их было бы
// ошибкой ровно того рода, о которой предупреждает `shared/i18n/config-client`:
// G7 держит уровни раздельно, и «сменил язык интерфейса — сменился язык
// агента» превратило бы три уровня в два. Здесь же locale отвечает на вопрос
// «что подставить в пустое поле», и ответ переписывается одним движением.

import type { Locale } from '../../donor/i18n/types'

/** Как язык называется в самой строке. Название пишется НА ЭТОМ ЖЕ языке —
 * инструкция «отвечай по-русски», написанная по-английски, работает хуже. */
const LANGUAGE_RULE: Partial<Record<Locale, string>> = {
  ru: 'Отвечай пользователю по-русски. Технические термины можно оставлять на английском.',
  en: 'Reply to the user in English.'
}

/**
 * Строка про язык для SOUL нового специалиста, или `''` — если для этой локали
 * правила нет.
 *
 * Пустая строка, а не английский запасной вариант: подставить «Reply in
 * English» человеку, выбравшему японский, значит молча решить за него — а
 * пустое поле хотя бы честно показывает, что решать ему.
 */
export function soulLanguageRule(locale: Locale): string {
  return LANGUAGE_RULE[locale] ?? ''
}
