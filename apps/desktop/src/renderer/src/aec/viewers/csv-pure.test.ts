import { describe, expect, test } from 'vitest'

import { detectDelimiter, parseCsv } from './csv-pure'

/**
 * Задача 4.3. Проверяется то, на чём ломается наивный `split(',')`: русский
 * Excel пишет через точку с запятой, потому что запятая у него внутри чисел.
 */

describe('определение разделителя', () => {
  test('русский Excel: точка с запятой, запятые внутри чисел', () => {
    const csv = 'Марка;Сечение;Длина\nВВГнг;2,5;13,4\nВВГ;1,5;7,2'

    expect(detectDelimiter(csv)).toBe(';')
    expect(parseCsv(csv)[1]).toEqual(['ВВГнг', '2,5', '13,4'])
  })

  test('обычный CSV с запятой', () => {
    expect(detectDelimiter('a,b,c\n1,2,3')).toBe(',')
  })

  test('табуляция', () => {
    expect(detectDelimiter('a\tb\tc\n1\t2\t3')).toBe('\t')
  })

  test('постоянство числа колонок важнее их количества', () => {
    // Запятых больше, но они пляшут по строкам — значит они внутри текста, а
    // разделитель это точка с запятой.
    const csv = 'Наименование;Примечание\nКабель;в лотке, по стене, скрыто\nЩит;у входа'

    expect(detectDelimiter(csv)).toBe(';')
    expect(parseCsv(csv)[1]).toEqual(['Кабель', 'в лотке, по стене, скрыто'])
  })

  test('одна колонка — разделять нечего', () => {
    expect(parseCsv('Кабель\nЩит')).toEqual([['Кабель'], ['Щит']])
  })
})

describe('разбор', () => {
  test('кавычки скрывают разделитель', () => {
    expect(parseCsv('"Кабель; в лотке";5', ';')).toEqual([['Кабель; в лотке', '5']])
  })

  test('удвоенная кавычка внутри кавычек — это одна кавычка', () => {
    expect(parseCsv('"провод ""А""";1', ';')).toEqual([['провод "А"', '1']])
  })

  test('перенос строки внутри кавычек не разрывает строку таблицы', () => {
    expect(parseCsv('"первая\nвторая";2', ';')).toEqual([['первая\nвторая', '2']])
  })

  test('CRLF — один конец строки', () => {
    expect(parseCsv('a;b\r\nc;d', ';')).toEqual([
      ['a', 'b'],
      ['c', 'd']
    ])
  })

  test('пустые ячейки сохраняются', () => {
    // Пустая ячейка в ведомости значима: пропустить её значит сдвинуть колонки.
    expect(parseCsv('a;;c', ';')).toEqual([['a', '', 'c']])
  })

  test('последняя строка без перевода в конце файла', () => {
    expect(parseCsv('a;b\nc;d\n', ';')).toEqual([
      ['a', 'b'],
      ['c', 'd']
    ])
  })

  test('пустой файл — пустая таблица', () => {
    expect(parseCsv('')).toEqual([])
  })
})
