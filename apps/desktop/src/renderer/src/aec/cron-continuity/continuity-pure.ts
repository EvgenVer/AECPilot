// Непрерывность контекста у расписаний (задача 3.5а, UR18).
//
// ЧТО ДЕЛАЕТ ЯДРО. У задачи cron есть поле `context_from`. Если в нём стоит
// `self`, планировщик перед КАЖДЫМ запуском находит самый свежий вывод этой же
// задачи и подклеивает его в начало задания с прямым указанием: «это вывод
// прошлого запуска, не повторяй уже сообщённое, продолжай с того же места»
// (`cron/scheduler.py`, обрезка на 8000 знаков). Нет прошлого вывода — молча
// ничего не подклеивается. Для нашего сценария G6 это разница между «со вчера
// появилось два новых листа» и слепым стартом каждое утро.
//
// ПОЧЕМУ ПЕРЕКЛЮЧАТЕЛЬ ОДИН НА ВСЕ ЗАДАЧИ. Поля `context_from` нет в интерфейсе
// донора — ни у нас, ни в их исходнике; это поле ядра, до которого их экран не
// доходит. Вшить галочку в их форму нельзя: это пятый вид правки вендорного
// файла, а разрешено четыре (AGENTS §14), и правка умерла бы при следующем
// переносе экрана. Решение владельца 2026-08-19 (интервью): один общий
// переключатель в нашем интерфейсе вместо галочки на каждой задаче.
//
// ПОЧЕМУ ПО УМОЛЧАНИЮ ВКЛЮЧЕНО. Все три сценария UR18 — ночной перескан
// источников, переиндексация, утренняя сводка изменений — это обнаружение
// ИЗМЕНЕНИЙ, где слепой старт и есть ошибка: задача каждый раз докладывает всё
// заново. Цена включённого состояния ограничена и известна: до 8000 знаков
// прошлого вывода в запросе. Выключатель существует ровно для исключений.

/** Значение `context_from`, означающее «свой прошлый вывод». Разбирается ядром
 * без учёта регистра, но пишем канонически. */
export const SELF_CONTEXT = 'self'

/** Тело запроса на создание задачи в том виде, в каком его строит их экран. */
export type CronCreateBody = Record<string, unknown>

/** Добавляет `context_from` в тело создания задачи, если непрерывность включена
 * и тело её ещё не несёт. Чужое значение не трогаем: если задача создаётся с
 * уже проставленным `context_from` (цепочка «задача А готовит — задача Б
 * разбирает»), общий переключатель не вправе это переписывать. */
export function withContinuity(body: unknown, enabled: boolean): unknown {
  if (!enabled) return body
  if (!body || typeof body !== 'object' || Array.isArray(body)) return body

  const record = body as CronCreateBody
  if (record.context_from !== undefined && record.context_from !== null) return body

  return { ...record, context_from: [SELF_CONTEXT] }
}

/** Что записать в задачу при переключении общего тумблера. Возвращает null,
 * если задачу трогать не надо.
 *
 * Включение проставляет `self` только тем, у кого поле пусто, — задача из
 * цепочки (её `context_from` указывает на ДРУГУЮ задачу) остаётся как есть.
 * Выключение снимает только `self`: снимать чужую ссылку общий тумблер не
 * вправе, он не про неё. */
export function continuityUpdateFor(
  job: { context_from?: unknown },
  enabled: boolean
): null | { context_from: null | string[] } {
  const current = job.context_from
  const isSelf =
    Array.isArray(current) &&
    current.length === 1 &&
    typeof current[0] === 'string' &&
    current[0].trim().toLowerCase() === SELF_CONTEXT

  if (enabled) {
    const empty =
      current === undefined || current === null || (Array.isArray(current) && current.length === 0)
    return empty ? { context_from: [SELF_CONTEXT] } : null
  }

  return isSelf ? { context_from: null } : null
}
