// Свежая установка следует теме ОС (задача 3.26, SPEC HX14).
//
// ЧТО УЖЕ РАБОТАЕТ. Их тема умеет режим `system`: он разрешается через
// `prefers-color-scheme` живым слушателем (`useMediaQuery` в
// `themes/context.tsx`), а `nativeTheme` в нашей сборке остаётся `system` —
// значит смена темы ОС меняет тему приложения без перезапуска. Ничего чинить
// не нужно.
//
// ЧТО НЕ ТАК. Их умолчание — `light` (`normalizeMode(null)`), поэтому на чистой
// установке приложение темы ОС НЕ слушается, пока человек сам не выберет
// «Системная» в оформлении. Возможность, которую надо найти в настройках, чтобы
// она появилась, — не та возможность, о которой говорит SPEC.
//
// ПОЧЕМУ ЗАСЕВ, А НЕ ПРАВКА ИХ УМОЛЧАНИЯ. `normalizeMode` вендорный, править
// его — пятый вид правки (AGENTS §14). Их значение хранится обычным ключом
// localStorage, и первый запуск — единственный момент, когда «ничего не
// выбрано» отличимо от «выбрано light». Записываем `system` только в этот
// момент; любой выбор человека (включая явный light) остаётся нетронутым.
//
// ПОЧЕМУ ЭТО ПЕРВЫЙ ИМПОРТ В `main.tsx`. Их модуль темы красит фон ещё на
// загрузке модуля, до React. Засев обязан случиться раньше, иначе первый кадр
// будет светлым на тёмной системе — мигание, а не ошибка, но лечится порядком.

/** Их ключ (`MODE_KEY`, `themes/context.tsx`). */
const MODE_KEY = 'hermes-desktop-mode-v1'

/** Ставит `system` умолчанием, если человек ещё ничего не выбирал. Возвращает
 * true, если засеял, — для теста. */
export function seedSystemThemeDefault(): boolean {
  try {
    if (window.localStorage.getItem(MODE_KEY) !== null) return false
    window.localStorage.setItem(MODE_KEY, 'system')
    return true
  } catch {
    // Хранилище недоступно — их модуль возьмёт своё умолчание, и это худшее,
    // что здесь может случиться.
    return false
  }
}

seedSystemThemeDefault()
