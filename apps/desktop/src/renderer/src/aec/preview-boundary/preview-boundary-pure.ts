// Граница вкладки предпросмотра (задача 3.4, SPEC HX13/UR22).
//
// ЧТО РЕШЕНО. Вкладка предпросмотра открывает только то, что произвёл агент:
// HTML-артефакт, файл проекта, изображение, локальную ссылку. Произвольный
// внешний URL в неё не загружается (HX13, решение владельца 2026-08-16).
// Основание записано в SPEC: ни один сценарий G1–G7 просмотра веба не требует,
// а `read_preview` в паре с внешней страницей делает любой сайт входом в
// контекст агента — то есть полным путём prompt-инъекции мимо R7, где мы
// контролируем только источники проекта.
//
// ПОЧЕМУ ПРОВЕРКА ЗДЕСЬ, А НЕ В ИХ КОДЕ. У донора одна дверь в предпросмотр
// (`openPreview`, `store/preview.ts`), и она вендорная: правка внутри неё была
// бы пятым видом правки (AGENTS §14 разрешает четыре) и умерла бы при
// следующем переносе. Зато список вкладок — обычный атом, и «внешняя вкладка
// не живёт» проверяется на нём: см. `install-preview-boundary.ts`.
//
// ЧТО ИМЕННО СЧИТАЕТСЯ ВНЕШНИМ. Вид `url` у них рождается ровно в одной ветке —
// `localPreviewTarget` при `^https?://` (`lib/local-preview.ts`), — поэтому вид
// и есть главный признак. Схема проверяется вторым слоем: цель могла прийти с
// той стороны моста (`normalizePreviewTarget`) с другим видом. Идентификатор
// артефакта под эту проверку не попадает: это slug реестра, а не адрес.

/** Ровно то, что нужно для решения; полная форма — их `PreviewTarget`. */
export interface PreviewTargetLike {
  kind: string
  url?: string
  source?: string
}

const REMOTE_SCHEME = /^(?:https?|ftp|ws|wss):/i

/** Внешняя ли это цель. Локальные пути, `file:`, `data:` и артефакты — нет. */
export function isExternalPreview(target: PreviewTargetLike): boolean {
  if (target.kind === 'url') return true
  return REMOTE_SCHEME.test(target.url ?? '') || REMOTE_SCHEME.test(target.source ?? '')
}

/** Что показать человеку в отказе: адрес, который он пытался открыть. Берётся
 * `source` (то, на что он нажал), а `url` — запасной вариант. */
export function refusedAddress(target: PreviewTargetLike): string {
  return (target.source ?? target.url ?? '').trim()
}
