// Установку начал агент — значит человек уже отвечает на их карточку
// (задача 3.8, решение владельца 2026-08-21).
//
// ПОЧЕМУ ЭТО ВООБЩЕ ЕСТЬ. Второй вход UR23 — инструмент `setup_mcp`: агент
// предлагает сервер, ядро блокируется внутри инструмента, а в ленте появляется
// ИХ карточка согласия с именем сервера и причиной. Дальше эта же карточка сама
// зовёт `POST /api/mcp/servers` — и наш гейт спрашивал во второй раз.
//
// Владелец решил гасить наш вопрос в этом случае. Основание: человек в этот
// самый момент отвечает на вопрос об этой самой установке, и второй диалог
// поверх первого — не защита, а помеха. Цена решения названа честно: команда
// запуска процесса и переменные окружения, которые показывает только наш
// диалог, при установке по предложению агента остаются невидимыми.
//
// КАК УЗНАЁМ. Их карточка держит запрос в своём хранилище до тех пор, пока не
// ответит ядру, а отвечает она ПОСЛЕ установки (`clearMcpSetupRequest` вызван
// внутри `respond`). Значит непустое хранилище на момент запроса и означает
// «этот вызов идёт из открытой карточки».

import { $mcpSetupRequests } from '../../donor/store/mcp-setup'

export function agentInstallInFlight(): boolean {
  return Object.keys($mcpSetupRequests.get()).length > 0
}
