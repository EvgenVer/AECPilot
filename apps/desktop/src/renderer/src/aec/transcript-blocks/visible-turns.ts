//
// ЧТО ДЕЛАЕТ ДОНОР. Их живой блок (`::preview`) умеет разговаривать с агентом:
// содержимое рамки зовёт `window.hermes.send(prompt)`, сообщение проходит через
// их же путь отправки — но помечается `displayKind: 'hidden'`. Строка в базе
// есть (контекст, возобновление, аудит), а пузыря в ленте нет: «перерисовка
// блока и есть ответ».
//
// ПОЧЕМУ У НАС ТАК НЕЛЬЗЯ. HTML этого блока пишет агент по прочитанным
// документам (R19). Замкнутая цепочка «документ → агент → HTML → снова агент»
// превращает команду, внедрённую в исходный документ, в путь, по которому агент
// отдаёт команды сам себе — мимо человека целиком. Решение владельца
// 2026-08-18: скрытых ходов не существует, сообщение из блока приходит в ленту
// как обычное.
//
// ГДЕ СТОИТ ПЕРЕХВАТ. Их просьба отправить — это событие окна
// `hermes:composer-submit` с `detail: {target, text, displayKind?}`. Мы снимаем
// только пометку, и делаем это прямо в `detail`: объект один на всех
// слушателей, а повторная отправка события потребовала бы гасить исходное — то
// есть больше кода ради того же результата. Ни одного вендорного файла править
// не нужно.
//
// ПОРЯДОК ВАЖЕН И ОБЕСПЕЧЕН. Слушатели на одной цели вызываются в порядке
// подписки; наш ставится из тела `main.tsx`, то есть до того, как смонтируется
// первый композер и подпишется их обработчик.
//
// ВТОРОЙ РУБЕЖ — В ГЛАВНОМ ПРОЦЕССЕ. `sanitizeRpcParams`
// (`main/gateway-passthrough-pure.ts`) снимает `display_kind: 'hidden'` с любого
// вызова, дошедшего до шлюза. Здесь — чтобы пузырь появился сразу, там — чтобы
// скрытой строки не оказалось в истории сессии, даже если этот перехват обойдут.
//
// ЧЕГО ПЕРЕХВАТ НЕ ТРОГАЕТ: их проверку и ограничения интента — длину, токен
// рамки и паузу между отправками. Это их код, он остаётся как есть.

const SUBMIT_EVENT = 'hermes:composer-submit'

interface SubmitDetail {
  displayKind?: 'hidden'
}

/** Снимает пометку «скрытый ход» со всех просьб отправить сообщение.
 * Возвращает функцию снятия — для тестов и симметрии. */
export function installVisibleTurns(): () => void {
  const listener = (event: Event): void => {
    const detail = (event as CustomEvent<SubmitDetail>).detail
    if (detail?.displayKind === 'hidden') delete detail.displayKind
  }

  window.addEventListener(SUBMIT_EVENT, listener)
  return () => window.removeEventListener(SUBMIT_EVENT, listener)
}
