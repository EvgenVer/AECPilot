// Русский каталог плагина «Канбан» (задача T27).
//
// У их плагина канбана каталог на en / ja / zh / zh-hant, русского нет — а доска
// агентов у нас живая (SPEC N10, T44), и без этого файла в русском интерфейсе она
// целиком английская. Каталог лежит у нас, а в таблицу локалей плагина
// (`donor/plugins/kanban/i18n.ts`, правка [3]) вписана одна строка `ru`. Там же он
// присвоен типу `KanbanMessages`: ключ, который они добавят выше по течению,
// станет ошибкой компиляции, а не английской строкой на русском экране.
//
// Словарь: карточка (card), доска (board), исполнитель (assignee), диспетчер
// (dispatcher), воркер (worker), профиль (profile) — как в остальном каталоге.
// Команда `hermes project` — то, что человек печатает в терминале; она остаётся
// буквальной, как и в английском каталоге (ей отведено место в
// `no-hermes-literals.test.ts`).
//
// Типы параметров указаны явно: у этого файла нет их типа для подсказки, а
// сверка с ним происходит на стороне донора.

// Русские формы числа: 1 вложение, 2 вложения, 5 вложений.
function plural(n: number, one: string, few: string, many: string): string {
  const d = n % 10
  const h = n % 100
  if (d === 1 && h !== 11) return one
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return few
  return many
}

