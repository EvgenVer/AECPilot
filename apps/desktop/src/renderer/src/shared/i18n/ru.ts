// До 0.21.2 у донора русского каталога не было, и здесь лежал НАШ частичный
// (104 строки: `common`, `language`, `tips`) поверх нашего английского. С
// подъёмом 3.B4 у донора появился полный `donor/i18n/ru.ts` — 3855 строк,
