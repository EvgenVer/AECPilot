// Алиас `@hermes/plugin-sdk` ведёт в перенесённый барьер (задача 3D.1).
//
// ЗАЧЕМ ТЕСТ НА ОДНУ СТРОКУ КОНФИГА. Их плагин специалистов импортирует этот
// путь в 37 из 45 не-тестовых файлов, и правка импорта в них НЕ входит в пять
// разрешённых видов правок зоны (AGENTS §14). То есть алиас — не удобство, а
// единственное, чем 37 файлов держатся неправлеными; уберите его, и перенос
// разваливается сразу весь, а не в одном месте.
//
// В ИХ дереве этот путь разрешается точно так же (`tsconfig.json`:
// "@hermes/plugin-sdk": ["./src/sdk/index.ts"]) — то есть мы не подменяем их
// модуль своим, а повторяем их же отображение, наведённое на нашу копию.
//
// Проверяется тождество модулей, а не наличие экспорта: алиас, уводящий в
// ДРУГУЮ копию SDK, дал бы два объекта `host` с раздельным состоянием — отказ,
// который на глаз не виден и проявился бы расхождением сессий.

import { describe, expect, it } from 'vitest'

import * as viaAlias from '@hermes/plugin-sdk'

import * as direct from '../donor/sdk'

describe('алиас плагинного SDK', () => {
  it('ведёт ровно в перенесённый барьер, а не во вторую его копию', () => {
    expect(viaAlias).toBe(direct)
  })

  it('через алиас виден `host` — то, чем плагин говорит с приложением', () => {
    expect(typeof viaAlias.host).toBe('object')
  })
})
