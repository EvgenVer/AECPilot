// Постоянный чат специалиста: какую сессию открыть (задача 3C.4, SPEC UR27).
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. У специалиста один непрерывный разговор — в этом
// вся идея: к нему обращаются как к человеку, а не заводят новую переписку на
// каждый вопрос. Значит привязка «специалист → сессия» обязана переживать
// перезапуск, сжатие истории, удаление сессии и недоступность ядра. Их код
// разбирает одиннадцать таких случаев отдельными тестами, и это не педантизм:
// ошибка здесь означает, что человек ПОТЕРЯЛ переписку со специалистом.
//
// ГЛАВНОЕ ПРАВИЛО: НЕ ЗАВОДИТЬ ВТОРОЙ ЧАТ ВСЛЕПУЮ. Разница между «чата точно
// нет» и «спросить не удалось» — это разница между «создать» и «отказать и
// предложить повторить». Второе состояние выглядит как первое и потому опаснее.
//
// Личность чата с 0.20.6 — его ИМЯ: сессия, названная «Bot Chat», и есть
// постоянный чат профиля (задача 3.B2б). Ядро отказывает в переименовании такой
// строки, пока она скрыта, — поэтому скрытость здесь несущая, а не косметика.

/** Что известно о постоянном чате к моменту решения. */
export interface CanonicalChatFacts {
  /**
   * Реестровая строка этого профиля — сессия, названная ровно «Bot Chat».
   *
   * Три состояния, и путать их нельзя:
   *   объект    — чат есть; `id` его личность, `resolvedId` живая вершина
   *               сжатой переписки (её и открывают);
   *   `null`    — реестр ответил и сказал «такой строки нет»;
   *   `undefined` — СПРОСИТЬ НЕ УДАЛОСЬ. Это не «нет».
   */
  registry?: { id: string; resolvedId: string } | null
  /**
   * Последняя сессия этого профиля, если ядро её показало. Нужна ровно для
   * дедушкиного правила ниже.
   */
  latest?: { id: string } | null
}

export type CanonicalChatPlan =
  /** Открыть эту сессию — она уже реестровая, трогать нечего. */
  | { action: 'open'; sessionId: string }
  /** Назвать эту существующую сессию «Bot Chat», скрыть и открыть. */
  | { action: 'adopt'; sessionId: string }
  /** Завести новую. */
  | { action: 'create' }
  /** Реестр не ответил — НЕ открывать и НЕ создавать (см. ниже). */
  | { action: 'refuse' }

/**
 * Решение по фактам.
 *
 * ЧТО ИЗМЕНИЛОСЬ В 0.20.6 (задача 3.B2б). Раньше личностью чата была НАША метка:
 * сохранённый номер сессии плюс метка источника `aecpilot-roster`. Ядро сняло
 * механизм, на котором это стояло, — параметра `preferred_session_ids` и поля
 * `preferred_session` больше нет, — и заменило его реестром: сессия, названная
 * «Bot Chat», И ЕСТЬ постоянный чат профиля, а уникальный индекс по заголовку
 * делает её единственной.
 *
 * Заголовок мы прежде отвергли (3C.4б) по причине, которая исчезла: его
 * переименовывал автоименователь модели. В 0.20.6 ядро отказывает в
 * переименовании скрытой строки с этим заголовком (#92473) — проверено на обеих
 * версиях, в 0.20.5 такого отказа нет. Разбор — `runtime/contracts/canonical-chat-0.20.6.md`.
 *
 * Правила, от частого к редкому:
 *
 * 1. реестр ответил и чат есть → открыть его вершину;
 * 2. реестр ответил, чата нет, но у профиля есть переписка → назвать её и
 *    усыновить («дедушкино правило»: у специалиста, заведённого до этой
 *    возможности, разговор уже идёт, и новый пустой чат выглядел бы как потеря);
 * 3. реестр ответил, ничего нет → создать;
 * 4. СПРОСИТЬ НЕ УДАЛОСЬ → отказать.
 *
 * ПОЧЕМУ ЧЕТВЁРТОЕ ПРАВИЛО ИМЕННО ОТКАЗ, А НЕ СОЗДАНИЕ. Это единственный
 * оставшийся способ раздвоить вечный чат, и он уже случался у донора: их сбой
 * жил ровно в окне после обновления — окно перезапускает бэкенды профилей,
 * первый клик обгоняет прогрев, поиск падает, а проглоченная ошибка уводила
 * прямо в `session.create`. Человек читает это как «специалист забыл всё».
 * Повторить попытку дёшево; завести второй чат поверх живого — нет.
 */
export function planCanonicalChat(facts: CanonicalChatFacts): CanonicalChatPlan {
  if (facts.registry === undefined) return { action: 'refuse' }

  if (facts.registry !== null) {
    const id = facts.registry.resolvedId === '' ? facts.registry.id : facts.registry.resolvedId
    return { action: 'open', sessionId: id }
  }

  if (facts.latest) return { action: 'adopt', sessionId: facts.latest.id }

  return { action: 'create' }
}

/**
 * Надо ли подменить `/new` очисткой контекста.
 *
 * `/new` в постоянном чате раскалывает разговор на две сессии — ровно то, чего
 * этот чат обещает не делать. Подменяется на `/compact`: ощущение то же (свежий
 * рабочий контекст), а переписка остаётся одна. В ОБЫЧНОЙ сессии того же
 * специалиста `/new` работает как везде — иначе мы отняли бы у человека
 * возможность начать с чистого листа вообще.
 */
export function rerouteNewInCanonicalChat(
  text: string,
  activeSessionId: string,
  canonicalSessionId: string
): string | null {
  if (activeSessionId === '' || canonicalSessionId === '') return null
  if (activeSessionId !== canonicalSessionId) return null

  return /^\/(new|reset)\s*$/.test(text.trim()) ? '/compact' : null
}
