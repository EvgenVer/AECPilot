// Постоянный чат специалиста: какую сессию открыть (задача 3C.4, SPEC UR27).
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. У специалиста один непрерывный разговор — в этом
// вся идея: к нему обращаются как к человеку, а не заводят новую переписку на
// каждый вопрос. Значит привязка «специалист → сессия» обязана переживать
// перезапуск, сжатие истории, удаление сессии и недоступность ядра. Их код
// разбирает одиннадцать таких случаев отдельными тестами, и это не педантизм:
// ошибка здесь означает, что человек ПОТЕРЯЛ переписку со специалистом.
//
// ГЛАВНОЕ ПРАВИЛО: НЕ ПЕРЕЗАПИСЫВАТЬ ПРИВЯЗКУ ВСЛЕПУЮ. Разница между «сессия
// точно исчезла» и «спросить не удалось» — это разница между «завести новую» и
// «ничего не трогать». Второе состояние выглядит как первое и потому опаснее.

/** Что известно о привязке к моменту решения. */
export interface CanonicalChatFacts {
  /** Сохранённая привязка (`ui_meta.aecpilot.chat`). Пусто — её нет. */
  pin: string
  /** Ответ ядра о привязанной сессии: `undefined` — не спрашивали или спросить
   * не удалось; `null` — ядро ответило «такой сессии нет». */
  preferred?: { id: string } | null
  /** Последняя сессия этого профиля, если ядро её показало. */
  latest?: { id: string } | null
  /** Удалось ли вообще получить ответ от ядра. `false` — сеть/ядро молчат. */
  answered: boolean
}

export type CanonicalChatPlan =
  /** Открыть эту сессию; привязку не трогать. */
  | { action: 'open'; sessionId: string }
  /** Открыть эту сессию и ЗАПИСАТЬ её как привязку (её ещё не было или старая
   * заведомо мертва). */
  | { action: 'adopt'; sessionId: string }
  /** Создать новую и записать. */
  | { action: 'create' }

/**
 * Решение по фактам.
 *
 * Порядок правил — от самого частого к самому редкому, и каждое из них взято из
 * их теста с тем же смыслом:
 *
 * 1. привязка есть и жива → открыть как есть («живая привязка не заменяется»);
 * 2. привязка есть, но спросить не удалось → тоже открыть как есть и НИЧЕГО не
 *    переписывать («недоступность ядра не повод терять переписку»);
 * 3. привязка есть, ядро сказало «нет такой» → взять последнюю сессию профиля,
 *    если она есть, и перепривязать на НЕЁ («перепривязка на показанную, а не
 *    на самую новую»);
 * 4. привязки нет, но история есть → усыновить последнюю («дедушкино правило»:
 *    у специалиста, заведённого до этой возможности, переписка уже есть, и
 *    новая пустая сессия выглядела бы как её потеря);
 * 5. ничего нет → создать.
 */
export function planCanonicalChat(facts: CanonicalChatFacts): CanonicalChatPlan {
  if (facts.pin !== '') {
    // Ядро не отвечало — привязка остаётся в силе. Это не оптимизм, а
    // единственный безопасный выбор: переписать её сейчас значит потерять
    // разговор из-за обрыва связи.
    if (!facts.answered || facts.preferred === undefined) {
      return { action: 'open', sessionId: facts.pin }
    }

    if (facts.preferred !== null) return { action: 'open', sessionId: facts.preferred.id }

    // Ядро ответило определённо: такой сессии нет.
    if (facts.latest) return { action: 'adopt', sessionId: facts.latest.id }
    return { action: 'create' }
  }

  if (facts.answered && facts.latest) return { action: 'adopt', sessionId: facts.latest.id }

  return { action: 'create' }
}

/**
 * Надо ли подменить `/new` очисткой контекста.
 *
 * `/new` в постоянном чате раскалывает разговор на две сессии — ровно то, чего
 * этот чат обещает не делать. Подменяется на `/compact`: ощущение то же (свежий
 * рабочий контекст), а переписка остаётся одна. В ОБЫЧНОЙ сессии того же
 * специалиста `/new` работает как везде — иначе мы отняли бы у человека
 * возможность начать с чистого листа вообще.
 */
export function rerouteNewInCanonicalChat(
  text: string,
  activeSessionId: string,
  canonicalSessionId: string
): string | null {
  if (activeSessionId === '' || canonicalSessionId === '') return null
  if (activeSessionId !== canonicalSessionId) return null

  return /^\/(new|reset)\s*$/.test(text.trim()) ? '/compact' : null
}
